const variant = (
  sku: string,
  color_name: string,
  color_slug: string,
  color_hex: string | null,
  price_fcfa: number,
  position: number,
  extras: Partial<ProductVariant> = {},
): ProductVariant => ({
  sku,
  color_name,
  color_slug,
  color_hex,
  storage_gb: null,
  size_mm: null,
  price_fcfa,
  stock: 18,
  low_stock_threshold: 3,
  is_default: position === 0,
  is_active: true,
  position,
  ...extras,
});

/** Coloris : nom affiché, slug, couleur d'aperçu, code court pour le SKU. */
type Finish = readonly [name: string, slug: string, hex: string, code: string];

const storageLabel = (gb: number) => (gb >= 1024 ? `${gb / 1024} To` : `${gb} Go`);
const storageCode = (gb: number) => (gb >= 1024 ? `${gb / 1024}T` : `${gb}`);

/** Une variante par coloris, au même prix. */
const colorVariants = (prefix: string, finishes: readonly Finish[], price: number) =>
  finishes.map(([name, slug, hex, code], position) =>
    variant(`${prefix}-${code}`, name, slug, hex, price, position),
  );

/** Coloris × capacités (`[Go, prix]`), coloris par coloris. */
const storageVariants = (
  prefix: string,
  finishes: readonly Finish[],
  capacities: readonly (readonly [gb: number, price: number])[],
) =>
  finishes.flatMap(([name, slug, hex, code], f) =>
    capacities.map(([gb, price], c) =>
      variant(
        `${prefix}-${code}-${storageCode(gb)}`,
        `${name} · ${storageLabel(gb)}`,
        slug,
        hex,
        price,
        f * capacities.length + c,
        { storage_gb: gb },
      ),
    ),
  );

/** Coloris × tailles de boîtier (`[mm, prix]`), coloris par coloris. */
const sizeVariants = (
  prefix: string,
  finishes: readonly Finish[],
  sizes: readonly (readonly [mm: number, price: number])[],
) =>
  finishes.flatMap(([name, slug, hex, code], f) =>
    sizes.map(([mm, price], s) =>
      variant(
        `${prefix}-${mm}-${code}`,
        `${mm} mm · ${name}`,
        slug,
        hex,
        price,
        f * sizes.length + s,
        {
          size_mm: mm,
        },
      ),
    ),
  );

